#!/usr/bin/env python3
import curses
import sys
from pathlib import Path

# __file__ is tools/config/configure.py
# .parents[0] = tools/config
# .parents[1] = tools
# .parents[2] = project root directory
ROOT_DIR = Path(__file__).resolve().parents[2]

CONFIG_FILE = ROOT_DIR / ".config"
HEADER_FILE = ROOT_DIR / "src" / "kernel" / "include" / "config.h"
MAKEFILE_FRAGMENT = ROOT_DIR / "src" / "kernel" / "include" / "config.mk"

# Macro naming convention:
#   MH_*        general Mach kernel features (ports, ...) - nothing to do with Mach-O
#   MHO_*   Mach-O support (the executable format + its loader)
#   SCHED_* scheduler policy
#   EXEC_*  executable formats that are neither Mach-O nor Mach specific
# Define configuration options
OPTIONS = [
        # "id": ID, "label": TITLE, "type": MULTICHOICE|CHOICE|BOOL, "group": CATEGORY, "default" TRUE|FALSE?

        # Executable Formats (Multi-choice: At least 1 required)
        {"id": "CONFIG_EXEC_ELF", "label": "ELF Executable Format", "type": "multichoice", "group": "exec", "default": True, "required": True},
        {"id": "CONFIG_MHO_EXEC", "label": "Mach-O Executable Format", "type": "multichoice", "group": "exec", "default": True, "required": True},

        # General Mach Features (Multi-choice: may all be disabled for a pure
        # POSIX-only kernel, CONFIG_MH then collapses to 0)
        {"id": "CONFIG_MH_PORTS", "label": "Mach Port Rights (IPC)", "type": "bool", "group": "mh", "default": True},

        # Scheduler Choice (Mutually Exclusive)
        {"id": "CONFIG_SCHED_ROUNDROBIN", "label": "Round-Robin Scheduler", "type": "choice", "group": "sched", "default": True},
        {"id": "CONFIG_SCHED_PRIORITY", "label": "Priority-Based Scheduler", "type": "choice", "group": "sched", "default": False},
        {"id": "CONFIG_SCHED_PRIORITYROUNDROBIN", "label": "Priority-Based Round Robin Scheduler", "type": "choice", "group": "sched", "default": False},

        # General Features
        {"id": "CONFIG_GENERIC_DBG", "label": "Compile debug build (-g, etc)", "type": "bool", "group": "general", "default": True},
]

# Group ordering + the heading printed above each group.
GROUPS = [
        ("exec", "Executable Formats"),
        ("mh", "Mach Features"),
        ("sched", "Scheduler"),
        ("general", "General"),
]

# Macro names are derived, never configured: they let code test a whole family
# with a single #if (e.g. "is any Mach feature compiled in at all?")
DERIVED = [
        ("CONFIG_EXEC", ["CONFIG_EXEC_ELF", "CONFIG_MHO_EXEC"]),
        ("CONFIG_MH", ["CONFIG_MH_PORTS"]),
        ("CONFIG_SCHED", ["CONFIG_SCHED_ROUNDROBIN", "CONFIG_SCHED_PRIORITY", "CONFIG_SCHED_PRIORITYROUNDROBIN"]),
]

def load_config():
        config = {opt["id"]: opt["default"] for opt in OPTIONS}
        if CONFIG_FILE.exists():
                with open(CONFIG_FILE, "r") as f:
                        for line in f:
                                if "=" in line:
                                        k, v = line.strip().split("=", 1)
                                        if k in config:
                                                config[k] = (v == "y")
        return config

def validate(config):
        for group, _title in GROUPS:
                members = [opt for opt in OPTIONS if opt["group"] == group]
                types = set(opt["type"] for opt in members)
                if types == {"choice"}:
                        if sum(1 for opt in members if config[opt["id"]]) != 1:
                                return "ERROR: Pick exactly one Scheduler!"
                elif types == {"multichoice"}:
                        # A group flagged required may not be emptied out entirely
                        if members[0].get("required") and not any(config[opt["id"]] for opt in members):
                                return "ERROR: You must select at least one Executable Format!"
        return None

def derived_value(config, sources):
        return 1 if any(config[k] for k in sources) else 0

def save_config(config):
        err = validate(config)
        if err:
                return err

        ROOT_DIR.mkdir(parents=True, exist_ok=True)

        HEADER_FILE.parent.mkdir(parents=True, exist_ok=True)

        with open(CONFIG_FILE, "w") as f:
                for k, v in config.items():
                        f.write(f"{k}={'y' if v else 'n'}\n")

        derived = {name: derived_value(config, sources) for name, sources in DERIVED}

        # generate config header
        with open(HEADER_FILE, "w") as f:
                f.write("/* Automatically generated by configure.py - DO NOT EDIT */\n")
                f.write("#ifndef CONFIG_H\n")
                f.write("#define CONFIG_H\n\n")
                for group, title in GROUPS:
                        f.write(f"/* {title} */\n")
                        for opt in OPTIONS:
                                if opt["group"] != group:
                                        continue
                                f.write(f"#define {opt['id']} {1 if config[opt['id']] else 0}\n")
                        f.write("\n")

                f.write("/* Derived: any feature of the family is compiled in */\n")
                for name, _sources in DERIVED:
                        f.write(f"#define {name} {derived[name]}\n")
                f.write("\n#endif /* CONFIG_H */\n")

        # generate the makefile fragment, so the build system can act on the same
        # configuration without having to parse the C header
        with open(MAKEFILE_FRAGMENT, "w") as f:
                f.write("# Automatically generated by configure.py - DO NOT EDIT\n")
                for k, v in config.items():
                        f.write(f"{k} := {1 if v else 0}\n")
                for name, _sources in DERIVED:
                        f.write(f"{name} := {derived[name]}\n")

        return None

def menu_rows():
        """Display order as (kind, payload): kind is 'title' (a string) or 'opt'."""
        rows = []
        for group, title in GROUPS:
                rows.append(("title", title))
                for opt in OPTIONS:
                        if opt["group"] == group:
                                rows.append(("opt", opt))
        return rows

def main_menu(stdscr):
        curses.curs_set(0)
        config = load_config()
        rows = menu_rows()
        current_row = next(i for i, (kind, _idx) in enumerate(rows) if kind == "opt")
        top = 0
        status_msg = "Use arrow UP|DOWN to move, SPACE to toggle/check/uncheck, ENTER to save & exit, 'q' to quit."

        while True:
                stdscr.clear()
                h, w = stdscr.getmaxyx()

                # titlebar
                title = " === HNU Kernel Config == "
                if w > len(title):
                        stdscr.addstr(0, (w - len(title)) // 2, title, curses.A_BOLD)

                # 2 lines of chrome on top (titlebar + blank), 2 on the bottom (status)
                view = h - 4
                if current_row < top:
                        top = current_row
                elif current_row >= top + view:
                        top = current_row - view + 1

                for screen_row, (kind, payload) in enumerate(rows[top:top + view]):
                        line_no = screen_row + 2
                        if kind == "title":
                                stdscr.addstr(line_no, 2, payload[:w - 4], curses.A_BOLD)
                                continue

                        opt = payload
                        prefix = "[*]" if config[opt["id"]] else "[ ]"
                        if opt["type"] == "choice":
                                prefix = "( * )" if config[opt["id"]] else "(   )"

                        line = f" {prefix} {opt['label']}"
                        line = line.ljust(w - 4)[:w - 4]
                        if top + screen_row == current_row:
                                stdscr.attron(curses.A_REVERSE)
                                stdscr.addstr(line_no, 2, line)
                                stdscr.attroff(curses.A_REVERSE)
                        else:
                                stdscr.addstr(line_no, 2, line)

                # status bar
                if h > 2:
                        stdscr.addstr(h - 2, 2, status_msg[:w - 4], curses.A_DIM)
                stdscr.refresh()

                key = stdscr.getch()
                if key == curses.KEY_UP and current_row > 0:
                        while current_row > 0 and rows[current_row - 1][0] == "title":
                                current_row -= 1
                        if current_row > 0:
                                current_row -= 1
                elif key == curses.KEY_DOWN and current_row < len(rows) - 1:
                        while current_row < len(rows) - 1 and rows[current_row + 1][0] == "title":
                                current_row += 1
                        if current_row < len(rows) - 1:
                                current_row += 1
                elif key == ord(' '):
                        opt = rows[current_row][1]
                        if opt["type"] == "bool" or opt["type"] == "multichoice":
                                config[opt["id"]] = not config[opt["id"]]
                        elif opt["type"] == "choice":
                                for o in OPTIONS:
                                        if o["group"] == opt["group"]:
                                                config[o["id"]] = (o["id"] == opt["id"])
                elif key in (10, 13, curses.KEY_ENTER):
                                err = save_config(config)
                                if err:
                                        status_msg = err
                                else:
                                        return  # let curses clean up.

                elif key == ord('q'):
                        return # q = exit

if __name__ == "__main__":
        if "--defaults" in sys.argv:
                # non-interactive: rewrite the generated files from the current .config
                # (or the built-in defaults when there is none)
                err = save_config(load_config())
                if err:
                        print(err, file=sys.stderr)
                        sys.exit(1)
        else:
                curses.wrapper(main_menu)
